def message_of(code: str) -> str:
    """그 코드의 예비 문구. 없으면 빈 글자입니다.

    **서버가 보낸 문구가 있으면 그것을 씁니다.** 이 값은 서버가 문구를 안 보내
    줄 때만 쓰는 자리이고, 차례는 `describe()` 가 지킵니다.
    """
    body = str(code or "").strip()
    return SYSTEM_MESSAGES.get(body) or ORDER_MESSAGES.get(body) or ""


def kind_of(code: str) -> str:
    """그 코드로 무엇을 해야 하는지. 모르는 코드는 `other` 입니다."""
    body = str(code or "").strip()
    if not body:
        return OTHER
    if body in KINDS:
        return KINDS[body]
    if body in OK_CODES:
        return OK
    return OTHER


def describe(code: Any, message: Any = "") -> dict[str, str]:
    """화면이 받는 모양 — 코드·문구·갈래.

    **문구 차례는 셋입니다.** 서버가 보낸 것 → 사전의 예비 문구 → 없으면 빈
    글자(화면에 코드만 남습니다). 사전이 원문을 덮지 않습니다.
    """
    body = str(code or "").strip()
    said = str(message or "").strip()
    return {
        "code": body,
        "message": said or message_of(body),
        "kind": kind_of(body),
    }


def failure_of(body: Any) -> dict[str, str] | None:
    """응답 본문이 실패를 담고 있으면 그 모양, 아니면 `None`.

    **HTTP 상태와 무관하게 봅니다.** 본문에 `errorCode` 가 있으면 200 이어도
    실패입니다. 다만 정상 처리에도 코드가 실려 오는 자리가 있어(`OK_CODES`)
    그것은 실패로 보지 않습니다.
    """
    if not isinstance(body, dict):
        return None

    code = str(body.get(ERROR_CODE_FIELD) or "").strip()
    if not code or code in OK_CODES:
        return None

    said = ""
    for field in ERROR_MESSAGE_FIELDS:
        said = str(body.get(field) or "").strip()
        if said:
            break
    return describe(code, said)


